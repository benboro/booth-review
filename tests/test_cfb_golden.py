def _sha(data: bytes) -> str:
    return hashlib.sha256(data).hexdigest()


def _frame_digest(frame: pl.DataFrame) -> str:
    return _sha(frame.write_ndjson().encode("utf-8"))


def _compute_digests(paths: DataPaths) -> dict[str, str]:
    """Digest every CFB build output, keyed by vault-relative path."""
    digests: dict[str, str] = {}
    site = paths.vault / "processed" / "site-data.json"
    digests["processed/site-data.json"] = _sha(site.read_bytes())
    for review in sorted((paths.vault / "interim").glob("*.csv")):
        digests[f"interim/{review.name}"] = _sha(review.read_bytes())
    for name in _PARQUET_TABLES:
        if name == "people":
            continue
        frame = pl.read_parquet(paths.vault / "processed" / f"{name}.parquet")
        digests[f"processed/{name}.parquet"] = _frame_digest(frame)
    digests[_PEOPLE_KEY] = _people_digest(paths)
    return digests


def _people_digest(paths: DataPaths) -> str:
    """people.parquet restricted to people on a telecast: the table may gain
    NFL-only rows (D-13), but never a CFB person's row changes."""
    people = pl.read_parquet(paths.vault / "processed" / "people.parquet")
    on_air = pl.read_parquet(paths.vault / "processed" / "telecast_people.parquet")["person_id"]
    kept = people.filter(pl.col("person_id").is_in(on_air.unique().to_list())).sort("person_id")
    return _frame_digest(kept)


def _build(git_vault: DataPaths, tmp_path: Path, reference: Path | None = None) -> Path:
    ref = _vault_with_sentinel_note(git_vault, tmp_path, _KNOWN_BOWLS)
    _write_manifest(git_vault, _CFB_MANIFEST)
    chosen = reference or ref
    run_build(git_vault, chosen, commit=False, accept_baseline=True)
    return ref


