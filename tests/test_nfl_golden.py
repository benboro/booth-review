def _sha(data: bytes) -> str:
    return hashlib.sha256(data).hexdigest()


def _frame_digest(frame: pl.DataFrame) -> str:
    # NDJSON, since nested columns break write_csv (same as test_cfb_golden).
    return _sha(frame.write_ndjson().encode("utf-8"))


def _compute_nfl_digests(paths: DataPaths) -> dict[str, str]:
    """Digest every NFL build output, keyed by vault-relative path."""
    digests: dict[str, str] = {_SITE: _sha((paths.vault / _SITE).read_bytes())}
    for review in sorted((paths.vault / "interim").glob("review_nfl_*.csv")):
        digests[f"interim/{review.name}"] = _sha(review.read_bytes())
    for table in sorted((paths.vault / "processed").glob("nfl_*.parquet")):
        digests[f"processed/{table.name}"] = _frame_digest(pl.read_parquet(table))
    return digests


@pytest.fixture
def nfl_vault(git_vault: DataPaths, tmp_path: Path, monkeypatch: pytest.MonkeyPatch) -> DataPaths:
    ref = tmp_path / "nfl_ref"
    shutil.copytree(REFERENCE, ref)
    monkeypatch.setenv("BOOTH_REVIEW_REFERENCE", str(ref))
    _seed(git_vault, rr=["NFL Network"])
    nfl_pipeline.run_nfl_build(
        git_vault,
        Path(os.environ["BOOTH_REVIEW_REFERENCE"]),
        seasons=[2014],
        include_playoffs=False,
        check_acceptance=False,
        commit=False,
        site_data=True,
    )
    return git_vault


def test_nfl_outputs_unchanged(nfl_vault: DataPaths) -> None:
    assert _compute_nfl_digests(nfl_vault) == _NFL_GOLDEN


def test_nfl_golden_covers_every_table(nfl_vault: DataPaths) -> None:
    written = {f"processed/{p.name}" for p in (nfl_vault.vault / "processed").glob("nfl_*.parquet")}
    pinned = {k for k in _NFL_GOLDEN if k.endswith(".parquet")}
    assert written == pinned
    assert _SITE in _NFL_GOLDEN
