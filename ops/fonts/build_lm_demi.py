"""Subset GUST's Latin Modern Roman Demi 10 into the site's serif woff2.

Offline and network-free. Usage:

    uv run python -I ops/fonts/build_lm_demi.py <source.otf> <out.woff2> <out_codepoints.py>

The source must be GUST's own ``lmromandemi10-regular.otf`` (SHA-256 pinned below); any
other file exits with code 2. The U+02BB (okina) cmap entry is aliased to the U+2018
glyph before subsetting, since Latin Modern has no okina. The subset is renamed, as the
GUST Font License asks of modified files. Needs fonttools and brotli (dev dependencies).
"""

from __future__ import annotations

import argparse
import hashlib
import sys
from pathlib import Path

from fontTools import subset
from fontTools.ttLib import TTFont

SOURCE_SHA256 = "63b6f9528e6117c5b0c0b1992517696ae09d05e7ca3711df0e0409d9db6df32c"
FAMILY_NAME = "Latin Modern Demi Subset"
POSTSCRIPT_NAME = "LMRomanDemi10-Subset"
OKINA = 0x02BB
LEFT_QUOTE = 0x2018

UNICODES = [
    *range(0x20, 0x7F),
    *range(0xA0, 0x180),
    0x2013,
    0x2014,
    0x2018,
    0x2019,
    0x201C,
    0x201D,
    0x2026,
    OKINA,
]


def _alias_okina(font: TTFont) -> None:
    for table in font["cmap"].tables:
        if table.isUnicode() and LEFT_QUOTE in table.cmap:
            table.cmap[OKINA] = table.cmap[LEFT_QUOTE]


def _rename(font: TTFont) -> None:
    name = font["name"]
    for name_id, value in ((1, FAMILY_NAME), (4, FAMILY_NAME), (16, FAMILY_NAME)):
        for record in list(name.names):
            if record.nameID == name_id:
                record.string = value
    for record in name.names:
        if record.nameID == 6:
            record.string = POSTSCRIPT_NAME


def _codepoints_module(codepoints: list[int]) -> str:
    lines: list[str] = []
    row: list[str] = []
    for value in codepoints:
        row.append(f"0x{value:04X},")
        if len(row) == 10:
            lines.append("        " + " ".join(row))
            row = []
    if row:
        lines.append("        " + " ".join(row))
    body = "\n".join(lines)
    return (
        "# Generated by ops/fonts/build_lm_demi.py from the shipped subset; do not edit.\n"
        "from __future__ import annotations\n\n"
        "SERIF_CODEPOINTS: frozenset[int] = frozenset(\n"
        "    {\n"
        f"{body}\n"
        "    }\n"
        ")\n"
    )


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0] if __doc__ else "")
    parser.add_argument("source", type=Path)
    parser.add_argument("out_woff2", type=Path)
    parser.add_argument("out_codepoints", type=Path)
    args = parser.parse_args(argv)

    digest = hashlib.sha256(args.source.read_bytes()).hexdigest()
    if digest != SOURCE_SHA256:
        print(f"refusing: {args.source} has SHA-256 {digest}, expected {SOURCE_SHA256}")
        return 2

    font = TTFont(args.source, recalcTimestamp=False)
    created = font["head"].created
    _alias_okina(font)

    options = subset.Options()
    options.flavor = "woff2"
    options.layout_features = ["kern", "liga", "ccmp"]
    options.notdef_outline = True
    options.name_IDs = [0, 1, 2, 3, 4, 5, 6, 13, 14, 16, 17]
    options.name_legacy = False
    options.name_languages = ["*"]
    options.recalc_timestamp = False
    subsetter = subset.Subsetter(options)
    subsetter.populate(unicodes=UNICODES)
    subsetter.subset(font)

    _rename(font)
    font["head"].modified = created
    args.out_woff2.parent.mkdir(parents=True, exist_ok=True)
    subset.save_font(font, str(args.out_woff2), options)

    saved = TTFont(args.out_woff2)
    codepoints = sorted(saved.getBestCmap())
    args.out_codepoints.write_text(_codepoints_module(codepoints), encoding="utf-8")

    data = args.out_woff2.read_bytes()
    print(f"{args.out_woff2}: {len(data)} bytes, SHA-256 {hashlib.sha256(data).hexdigest()}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
